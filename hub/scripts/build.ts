// Builds standalone hub binaries with the web app embedded.
//   bun run scripts/build.ts                 -> all targets
//   bun run scripts/build.ts linux-x64       -> one target
import { readdirSync, statSync, writeFileSync, mkdirSync, existsSync, readFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { $ } from "bun";

const ROOT = resolve(import.meta.dir, "../..");
const HUB = join(ROOT, "hub");
const WEB_DIST = join(ROOT, "web/dist");
const GEN = join(HUB, "src/web-assets.gen.ts");
const OUT = join(HUB, "out");
const STUB = `// Replaced by scripts/build.ts when compiling the hub binary. Keep this stub committed.\nexport const ASSETS: Record<string, string> = {};\n`;

const ALL = ["linux-x64", "linux-arm64", "darwin-arm64", "darwin-x64"];
const targets = process.argv.slice(2).length ? process.argv.slice(2) : ALL;

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

console.log("• building web app");
await $`bun run build`.cwd(join(ROOT, "web")).quiet();
if (!existsSync(join(WEB_DIST, "index.html"))) throw new Error("web build missing");

const files = walk(WEB_DIST);
const lines = ["// GENERATED by scripts/build.ts — do not commit"];
const entries: string[] = [];
files.forEach((f, i) => {
  const rel = relative(WEB_DIST, f).split("\\").join("/");
  lines.push(`import f${i} from ${JSON.stringify(relative(join(HUB, "src"), f).split("\\").join("/"))} with { type: "file" };`);
  entries.push(`  ${JSON.stringify("/" + rel)}: f${i},`);
});
lines.push("export const ASSETS: Record<string, string> = {", ...entries, "};", "");
writeFileSync(GEN, lines.join("\n"));
console.log(`• embedded ${files.length} web files`);

mkdirSync(OUT, { recursive: true });
const version = JSON.parse(readFileSync(join(HUB, "package.json"), "utf8")).version;
try {
  for (const t of targets) {
    const outfile = join(OUT, `crosstalk-hub-${t}`);
    console.log(`• compiling ${t}`);
    await $`bun build --compile --minify --sourcemap=none --target=bun-${t} ./src/main.ts --outfile ${outfile}`.cwd(HUB).quiet();
    const size = (statSync(outfile).size / 1e6).toFixed(1);
    console.log(`  ${relative(ROOT, outfile)} (${size} MB)`);
  }
} finally {
  writeFileSync(GEN, STUB);
}
console.log(`done · hub ${version}`);
